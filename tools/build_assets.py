def material(hex):
 if hex not in materials:
  m=bpy.data.materials.new(hex); m.diffuse_color=(*[int(hex[i:i+2],16)/255 for i in (1,3,5)],1); materials[hex]=m
 return materials[hex]
def box(x,z,y,w,d,h,col,bevel=0):
 bpy.ops.mesh.primitive_cube_add(size=1,location=(x,-z,y+h/2)); o=bpy.context.object; o.scale=(w,d,h); bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
